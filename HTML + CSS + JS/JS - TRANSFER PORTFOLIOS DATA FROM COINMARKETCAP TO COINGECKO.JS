function CONVERT_DATETIME_TO_TIMESTAMP(originalTime) {
  // 1. TẠO ĐỐI TƯỢNG DATE
  const zDATE = new Date(originalTime);
  // 2. LẤY HIỆU SỐ MÚI GIỜ (PHÚT) SO VỚI UTC
  const OFFSET = 0;
  // 3. ĐIỀU CHỈNH THỜI GIAN SANG UTC BẰNG CÁCH TRỪ ĐI OFFSET (CHUYỂN THÀNH MILI GIÂY)
  const UTCDATE = new Date(zDATE.getTime() - OFFSET * 60 * 1000);
  // 4. SỬ DỤNG TOISOSTRING() ĐỂ ĐỊNH DẠNG THÀNH TIMESTAMP UTC
  return UTCDATE.toISOString();
}

function EXTRACT_DATA(DATA) {
  const FIELDS = DATA.split('","');
  const TIME = FIELDS[0].replaceAll('"', "");
  var PRICE = FIELDS[3].replaceAll('"', "").replaceAll(",", "");
  PRICE = PRICE.split(".");
  PRICE = PRICE[0];
  const QUANTITY = FIELDS[4].replaceAll('"', "");
  var TYPE = FIELDS[2].replaceAll('"', "");
  if (TYPE == "buy") {
    TYPE = "buy";
  }
  if (TYPE == "transferIn") {
    TYPE = "transfer_in";
  }
  return {
    TIME: TIME,
    PRICE: PRICE,
    QUANTITY: QUANTITY,
    TYPE: TYPE,
  };
}

